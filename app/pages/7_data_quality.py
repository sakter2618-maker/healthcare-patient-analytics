from pathlib import Path

import pandas as pd
import streamlit as st

from app import ui

ROOT = Path(__file__).resolve().parents[2]
ui.hero("Data Cleaning & SQL", "How the raw hospital export was cleaned with Python, loaded into PostgreSQL and "
        "checked. All data is synthetic: no real patient information is used.",
        tags=["Python · pandas", "PostgreSQL", "Excel"])

log = pd.read_csv(ROOT / "docs" / "cleaning_log.csv")
raw_a = pd.read_csv(ROOT / "data" / "raw" / "admissions_raw.csv", dtype=str)
clean_a = pd.read_csv(ROOT / "data" / "clean" / "admissions.csv")
ui.kpi_row([
    ui.kpi("Raw admission rows", f"{len(raw_a):,}", "as exported", ui.ORANGE, "📥"),
    ui.kpi("Clean admission rows", f"{len(clean_a):,}", f"{len(raw_a) - len(clean_a):,} duplicates removed", ui.TEAL, "✅"),
    ui.kpi("Cleaning steps", f"{len(log)}", f"{log.rows_affected.sum():,} cell/row fixes", ui.VIOLET, "🧹"),
    ui.kpi("SQL ↔ Python check", "match", "readmissions recomputed in SQL", ui.GOOD, "🔍"),
])

ui.section("What the cleaning fixed", "Same log as docs/cleaning_log.csv and the Excel workbook.")
st.dataframe(log, hide_index=True, width="stretch", column_config={
    "table": "Table", "step": "Step", "rows_affected": st.column_config.NumberColumn("Rows", format="%d"),
    "action": st.column_config.TextColumn("What was done", width="large")})

c1, c2 = st.columns(2)
with c1:
    ui.section("Before: raw export sample")
    st.dataframe(raw_a[raw_a.department.str.lower().ne(raw_a.department) | raw_a.treatment_cost.str.contains(r"\$", na=False)]
                 .head(8)[["admission_id", "department", "gender", "admit_datetime", "treatment_cost", "readmission_risk"]],
                 hide_index=True, width="stretch")
with c2:
    ui.section("After: clean")
    st.dataframe(clean_a.head(8)[["admission_id", "department", "gender", "admit_datetime", "treatment_cost",
                                  "readmission_risk"]], hide_index=True, width="stretch")

ui.section("PostgreSQL star schema", "sql/01_schema.sql · 02_load_data.sql · 03_business_queries.sql (18 queries) · "
           "04_views_for_power_bi.sql")
st.code("""dim_hospital ─┐                    ┌─ dim_patient (de-identified)
dim_department┼── fact_admission ───┤
dim_date ─────┘   (21,723 stays)    └─ readmitted_30d from LEAD() over each patient's stays
dim_hospital / dim_department / dim_patient / dim_date ── fact_appointment (48,000)""", language=None)
st.code("""-- Q4: 30-day readmission rate, recomputed from the stay sequence
WITH seq AS (
  SELECT discharge_datetime,
         LEAD(admit_datetime) OVER (PARTITION BY patient_key ORDER BY admit_datetime) AS next_admit
  FROM fact_admission)
SELECT round(100.0 * avg(coalesce(next_admit - discharge_datetime
             BETWEEN interval '0' AND interval '30 days', false)::int), 1) AS readmission_rate_pct
FROM seq;   -- 15.5, identical to the Python result""", language="sql")

ui.callout("<b>About the data:</b> generated by <code>src/generate_data.py</code> with a fixed seed, so every number "
           "is reproducible. Hospital names are fictional and patient keys are random IDs. The raw export "
           "deliberately contains the problems real hospital exports have (duplicates, mixed date formats, "
           "text costs, label variants, impossible values) so the cleaning step has real work to do.")
ui.footer()
