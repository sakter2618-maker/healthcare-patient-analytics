"""
build_report.py — writes reports/Healthcare_Insights_Report.md from metrics.py,
so every number in the report is the same number the dashboard shows.

Run:  python src/build_report.py
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

import metrics as m

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "reports" / "Healthcare_Insights_Report.md"


def table(df: pd.DataFrame, fmts: dict) -> str:
    cols = list(fmts)
    out = ["| " + " | ".join(fmts[c][0] for c in cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(fmts[c][1].format(r[c]) for c in cols) + " |")
    return "\n".join(out)


def main():
    d = m.load()
    a, p, h = d["admissions"], d["appointments"], d["hospitals"]
    k = m.kpis(a, p)
    dep = m.admissions_by_department(a)
    cost = m.cost_by_department(a)
    hp = m.hospital_performance(a, p, h)
    demo = m.demographics(a, p)
    r = m.readmission_summary(a)
    n = m.noshow_summary(p)
    lead = m.noshow_by(p, "lead_time_band", m.BAND_ORDER)
    season = m.seasonality(a)
    winter = season[season.month.isin([12, 1, 2])].admissions_per_month.mean()
    rest = season[~season.month.isin([12, 1, 2])].admissions_per_month.mean()
    best, worst = hp.iloc[0], hp.iloc[-1]
    extra_days = (worst.avg_los - hp.avg_los.median()) * worst.admissions
    old = demo.set_index("age_group").loc["60+"]
    young_ns = m.noshow_by(p, "age_group").set_index("age_group").loc["18-30", "noshow_rate"]
    same_day = lead.set_index("lead_time_band").loc["Same day", "noshow_rate"]
    obs = a[a.readmitted_30d.notna()]
    target_gap = (r["rate"] - 14) / 100 * len(obs) / 2          # readmissions per year above a 14% target
    ans = m.business_answers(d)

    md = f"""# Healthcare Insights Report
**Healthcare Patient Analytics** · Salma Akter · data Jan 2024 – Dec 2025

> All data is **synthetic and de-identified** (generated by `src/generate_data.py`); hospital names are
> fictional and no real patient information is used. Every number below is produced by `src/metrics.py`
> and matches the dashboard, the SQL queries and the Excel workbook.

## 1. Executive summary

| KPI | Value |
|---|---|
| Admissions (inpatient stays) | {k['admissions']:,} ({k['patients']:,} patients) |
| Average length of stay | {k['avg_los']:.1f} days (median {k['median_los']:.1f}) |
| Average treatment cost per stay | ${k['avg_cost']:,.0f} (total ${k['total_cost'] / 1e6:,.1f}M) |
| 30-day readmission rate | **{k['readmission_rate']:.1f}%** (target 14%) |
| Appointments | {k['appointments']:,} |
| Appointment no-show rate | **{k['noshow_rate']:.1f}%** (+{k['cancel_rate']:.1f}% cancelled) |

**Three things to act on**

1. **{worst.hospital_name}** readmits {worst.readmission_rate:.1f}% of patients ({worst.readmission_rate - best.readmission_rate:+.1f} pts
   vs {best.hospital_name}) and keeps them {worst.avg_los - best.avg_los:.1f} days longer. Matching the median stay
   would free about **{extra_days:,.0f} bed-days** over the two years.
2. **Patients aged 60+** use {old.service_share:.1f}% of all services, stay {old.avg_los:.1f} days on average and are
   readmitted {old.readmission_rate:.1f}% of the time: the group where discharge planning pays off most.
3. **No-shows rise with waiting time:** {same_day:.1f}% for same-day bookings vs {n['long_lead']:.1f}% when booked more
   than 30 days ahead, and {n['sms_no']:.1f}% without an SMS reminder vs {n['sms_yes']:.1f}% with one.

## 2. Business questions

| Question | Answer | Detail |
|---|---|---|
""" + "\n".join(f"| {x['q']} | **{x['a']}** | {x['d']} |" for x in ans) + f"""

## 3. Patient admissions

* {k['admissions']:,} stays from {k['patients']:,} patients; {k['emergency_share']:.1f}% came in through the emergency department.
* **Seasonality:** winter months (Dec–Feb) average **{winter:,.0f} admissions/month** vs {rest:,.0f} the rest of the year
  (+{100 * (winter / rest - 1):.0f}%), driven by General Medicine and Pediatrics (respiratory season).

{table(dep, {"department": ("Department", "{}"), "admissions": ("Admissions", "{:,.0f}"), "share": ("Share", "{:.1f}%"),
             "emergency_share": ("Emergency %", "{:.1f}%"), "avg_los": ("Avg stay (days)", "{:.2f}")})}

## 4. Hospital performance

{table(hp, {"hospital_name": ("Hospital", "{}"), "admissions": ("Admissions", "{:,.0f}"), "avg_los": ("Avg stay", "{:.2f}"),
            "readmission_rate": ("Readmission %", "{:.1f}%"), "avg_recovery": ("Recovery", "{:.1f}"),
            "avg_cost": ("Avg cost", "${:,.0f}"), "noshow_rate": ("No-show %", "{:.1f}%"),
            "performance_score": ("Score", "{:.0f}")})}

*Score: relative, 100 = best of the five, 50 = weakest (readmissions 35%, stay 25%, recovery 25%, no-shows 15%).*

The gap at {worst.hospital_name.split()[0]} is persistent quarter after quarter, not a one-off, and comes with
the lowest recovery score at discharge ({worst.avg_recovery:.1f}). Long stays (> 10 days) cluster there in
Cardiology, Oncology and Neurology (SQL query 10).

## 5. Length of stay & treatment cost

{table(cost, {"department": ("Department", "{}"), "avg_cost": ("Avg cost", "${:,.0f}"), "median_cost": ("Median", "${:,.0f}"),
              "cost_per_day": ("Cost / bed-day", "${:,.0f}"), "total_cost": ("Total", "${:,.0f}")})}

* **{cost.department[0]}** has the highest average cost (${cost.avg_cost[0]:,.0f}), {cost.avg_cost[0] / cost.avg_cost.iloc[-1]:.1f}× {cost.department.iloc[-1]}.
* Surgery roughly **doubles** the cost of a stay in every department (see the cost-by-treatment matrix).
* Cost is driven by both price per day and days: Orthopedics has the highest cost per bed-day, Oncology the longest stays.

## 6. Readmissions

* **{r['rate']:.1f}%** of stays were followed by another admission within 30 days ({r['readmissions']:,} stays).
  Stays discharged in the final 30 days of data are excluded because their window is not complete.
* By age: 0-17 {demo.set_index('age_group').loc['0-17', 'readmission_rate']:.1f}% · 18-60 about {demo.set_index('age_group').loc[['18-30', '31-45', '46-60'], 'readmission_rate'].mean():.1f}% · **60+ {old.readmission_rate:.1f}%**.
* The discharge risk score separates patients well enough to act on: stays scored 25%+ ({r['high_risk_share']:.1f}% of stays)
  are readmitted **{r['rate_high_risk']:.1f}%** of the time vs {r['rate_low_risk']:.1f}% for the rest. It is a screening
  tool (AUC ≈ 0.61), not a diagnosis.
* Bringing the rate down to the 14% target would mean about **{target_gap:,.0f} fewer readmissions a year**.

## 7. Patient demographics

{table(demo, {"age_group": ("Age group", "{}"), "patients": ("Patients", "{:,.0f}"), "admissions": ("Admissions", "{:,.0f}"),
              "appointments": ("Appointments", "{:,.0f}"), "service_share": ("Share of services", "{:.1f}%"),
              "admissions_per_patient": ("Stays / patient", "{:.2f}")})}

## 8. Appointments & no-shows

* **{n['rate']:.1f}%** no-show rate = {n['no_shows']:,} missed visits, about **{n['missed_slots_per_week']:,.0f} empty slots a week**.
* Lead time is the strongest driver:

{table(lead, {"lead_time_band": ("Booked ahead", "{}"), "appointments": ("Appointments", "{:,.0f}"), "noshow_rate": ("No-show %", "{:.1f}%")})}

* 18-30 year olds miss {young_ns:.1f}% of appointments; Mondays and Fridays are the worst days.

## 9. Recommendations

| Priority | Action | Evidence | Expected effect |
|---|---|---|---|
| High | Readmission review at {worst.hospital_name} (discharge checklist, follow-up clinic within 7 days) | {worst.readmission_rate:.1f}% vs {best.readmission_rate:.1f}% at {best.hospital_name}; +{worst.avg_los - best.avg_los:.1f} days per stay | Closing half the gap ≈ {(worst.readmission_rate - best.readmission_rate) / 2 / 100 * worst.admissions / 2:,.0f} fewer readmissions/yr |
| High | Nurse call within 72 h for every stay with risk score ≥ 25% | {r['rate_high_risk']:.1f}% of these patients come back vs {r['rate_low_risk']:.1f}% | Targets the group most likely to return |
| High | SMS reminder for every appointment (today {100 * (p.sms_reminder == 'No').mean():.0f}% get none) + a second reminder when booked 30+ days ahead | {n['sms_no']:.1f}% vs {n['sms_yes']:.1f}% no-show; {n['long_lead']:.1f}% for long waits | Recovers part of the {n['missed_slots_per_week']:,.0f} missed slots per week |
| Medium | Winter staffing plan for General Medicine and Pediatrics | +{100 * (winter / rest - 1):.0f}% admissions Dec–Feb | Fewer delayed admissions in peak season |
| Medium | Geriatric discharge planning (medication review, home-care referral) | 60+: {old.readmission_rate:.1f}% readmitted, {old.avg_los:.1f}-day stays | Shorter stays and fewer returns |
| Low | Targeted overbooking for 18-30 on Monday/Friday slots | {young_ns:.1f}% no-show for 18-30 | Better clinic utilisation |

## 10. Method & data

* **Data:** synthetic hospital dataset (5 hospitals, 6 departments, Jan 2024 – Dec 2025) built on the columns of
  the original sample (age group, gender, region, department, treatment type, visit type, length of stay,
  treatment cost, recovery score, readmission risk) plus hospitals, appointments and actual readmissions.
* **Cleaning (Python):** {len(pd.read_csv(ROOT / 'docs' / 'cleaning_log.csv'))} logged steps: duplicates, label variants, mixed date
  formats, text costs, swapped dates, percentage-typed risk, impossible age codes, missing values (see `docs/cleaning_log.csv`).
* **Database (PostgreSQL):** star schema, 18 business queries; the readmission rate is recomputed in SQL with
  `LEAD()` and matches Python exactly.
* **Excel:** the cleaning workbook recalculates every KPI with formulas (zero errors).
* **Limitations:** synthetic data shows realistic patterns but not real clinical outcomes; the readmission
  definition is all-cause (any return within 30 days, planned or not).
"""
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(md)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(md.splitlines())} lines)")


if __name__ == "__main__":
    main()
